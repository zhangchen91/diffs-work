/**
 * The things the docs say about the repository are true of the repository.
 *
 * Seven times a page described something that was not there: four commands that do not run, two
 * directories that do not exist, and an extension permission table that listed a permission it does
 * not request while omitting the broad one it does. Each was found by eye, after the fact.
 *
 * This checks what can be checked mechanically — file paths the docs name, and the permissions the
 * extension actually declares — so the next one is found by a test.
 *
 *   node scripts/check-docs-truth.mjs
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const DOCS = path.join(ROOT, "apps/docs/src/content");

function* mdx(dir) {
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) yield* mdx(full);
    else if (/\.mdx?$/.test(name)) yield full;
  }
}

const failures = [];

/** Paths a reader is expected to create by building, or that the repo keeps private. */
const EXPLAINED_ABSENT = [
  [/\/dist\/?$/, "a build output — the page says to build it first"],
  [/^apps\/engine-core\b/, "the private Rust crate, gitignored on purpose"],
];

function whyAbsent(p) {
  for (const [re, why] of EXPLAINED_ABSENT) if (re.test(p)) return why;
  return "unknown";
}

/** Tracked by git, or present but gitignored — either way the repository stands behind the path. */
function trackedOrIgnored(p) {
  try {
    execFileSync("git", ["ls-files", "--error-unmatch", p], { cwd: ROOT, stdio: "ignore" });
    return true;
  } catch {
    try {
      execFileSync("git", ["check-ignore", "-q", p], { cwd: ROOT, stdio: "ignore" });
      return true;
    } catch {
      return false;
    }
  }
}
const isPlaceholder = (p) => /yourformat|your-format|\/\.\.\.|<|>|\$/.test(p);

for (const file of mdx(DOCS)) {
  const rel = path.relative(ROOT, file);
  const text = readFileSync(file, "utf8");

  // A backticked path that starts with a top-level directory of this repo should exist. Placeholder
  // paths (`test-cases/yourformat/`) are how a contributing guide names a file the reader creates.
  for (const m of text.matchAll(/`((?:apps|packages|scripts|test-cases)\/[^`\s]+)`/g)) {
    const p = m[1].replace(/[.,;:]$/, "");
    if (isPlaceholder(p)) continue;
    const abs = path.join(ROOT, p.replace(/\/$/, ""));
    if (existsSync(abs)) {
      // Present on disk but possibly not in the repository — checked below.
      if (!trackedOrIgnored(p)) failures.push(`${rel}: names \`${p}\`, which exists only on this machine`);
      continue;
    }
    // Absent here. Two legitimate reasons: it is a build output the reader is told to create
    // (`apps/chrome-extension/dist`, "build it first"), or it is gitignored on purpose
    // (`apps/engine-core`, the private crate). Anything else is a broken reference.
    const reason = whyAbsent(p);
    if (reason === "unknown") failures.push(`${rel}: names \`${p}\`, which does not exist`);
  }
}

// The extension's permission table is prose, so compare it against the manifest by name rather than
// by parsing the table: every permission the manifest declares must be mentioned somewhere on that
// page, and no permission the page lists may be absent from the manifest.
const manifestPath = path.join(ROOT, "apps/chrome-extension/manifest.json");
if (existsSync(manifestPath)) {
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const declared = new Set([...(manifest.permissions ?? []), "host_permissions"]);
  for (const lang of ["integrate/chrome-extension.mdx", "en/integrate/chrome-extension.mdx"]) {
    const file = path.join(DOCS, "docs", lang);
    if (!existsSync(file)) continue;
    const text = readFileSync(file, "utf8");
    for (const perm of declared) {
      if (!text.includes(perm)) failures.push(`${lang}: the manifest declares \`${perm}\` and the page does not mention it`);
    }
    for (const m of text.matchAll(/`(scripting|webRequest|tabs|cookies|downloads|history)`/g)) {
      if (!declared.has(m[1])) failures.push(`${lang}: the page names \`${m[1]}\`, which the manifest does not request`);
    }
  }
}

// The samples the site shows must be `test-cases/all-ops/`, not a copy that drifted. Sync runs in
// place; if it changes anything, a fixture was edited in one place and not the other.
try {
  // The published tree is gitignored and generated by `pnpm sync:examples`, so on a fresh checkout
  // it does not exist at all. Build it first when it is absent, then compare — but never rebuild it
  // when it is present, because that is what would hide a divergence.
  const published = path.join(ROOT, "apps/website/public/examples/allops");
  if (!existsSync(published)) {
    execFileSync(process.execPath, ["scripts/sync-examples.mjs"], { cwd: ROOT, stdio: "ignore" });
  }
  // Compare the two trees directly rather than running the sync: the sync would overwrite the
  // divergence and report nothing, which is how the first version of this check passed while a
  // tampered sample sat in the tree.
  const pairs = [];
  for (const name of readdirSync(path.join(ROOT, "test-cases/all-ops"))) {
    const src = path.join(ROOT, "test-cases/all-ops", name);
    // Same exclusions the sync applies: the expectations file is for tests, not the site.
    if (!statSync(src).isFile() || name.endsWith("expected.json")) continue;
    for (const dest of ["apps/website/public/examples/allops", "apps/local/public/examples/allops"]) {
      pairs.push([src, path.join(ROOT, dest, name), `${dest}/${name}`]);
    }
  }
  for (const [src, dest, label] of pairs) {
    if (!existsSync(dest)) {
      failures.push(`the published sample ${label} is missing`);
      continue;
    }
    if (!readFileSync(src).equals(readFileSync(dest))) {
      failures.push(`the published sample ${label} differs from test-cases/all-ops/${path.basename(src)}`);
    }
  }
} catch (e) {
  failures.push(`could not compare the samples: ${String(e).slice(0, 160)}`);
}

// A test that hardcodes /Users/<someone> passes here and fails on every runner. That happened three
// times in this repository's last day; this makes the fourth one impossible. Only tests and the
// scripts `pnpm test` runs are scanned — one-off generators may point at local checkouts.
try {
  const scan = [];
  for (const root of ["apps", "packages"]) {
    const dir = path.join(ROOT, root);
    if (!existsSync(dir)) continue;
    for (const app of readdirSync(dir)) {
      const tests = path.join(dir, app, "test");
      if (!existsSync(tests)) continue;
      for (const name of readdirSync(tests)) {
        if (/\.(mjs|js|ts)$/.test(name)) scan.push(path.join(tests, name));
      }
    }
  }
  for (const file of scan) {
    const text = readFileSync(file, "utf8");
    if (/\/Users\/[A-Za-z]/.test(text)) {
      failures.push(`${path.relative(ROOT, file)} hardcodes a home directory; resolve from import.meta.url instead`);
    }
  }
} catch (e) {
  failures.push(`could not scan tests for absolute paths: ${String(e).slice(0, 120)}`);
}

if (failures.length) {
  console.error(`\nFAILURES (${failures.length}):\n` + failures.slice(0, 30).map((f) => "  - " + f).join("\n"));
  process.exit(1);
}
console.log("[docs-truth] every path the docs name exists, and the extension page matches its manifest");
